//let vs const
//let allows you to change the value of a variable later on, while const does not allow you to change the value of a variable once it has been assigned.

//let
let x=5;
x=10; // This is allowed
console.log(x); // Output: 10

//const
const pi=3.14159;
pi=3.14; // This will throw an error because pi is a constant and cannot be reassigned

